"""SQLAlchemy Core table definitions for the ``objects``/``edges`` tables
(task-packets/E1-T05.yaml derived_decisions: "one generic revisioned objects
table plus one typed edges table, not per-entity tables"), the
``domain_events``/``outbox`` tables (task-packets/E1-T06.yaml), the
``processed_ids`` table (task-packets/E5-T07.yaml), the ``key_revocations``
table (task-packets/E5-T07b.yaml), and the ``pending_deliveries`` table
(task-packets/E6-T06.yaml).

Core ``Table`` objects are used deliberately instead of the ORM's declarative
classes — less magic under mypy strict, and these tables are accessed only
through the repository implementations in
``mrr.persistence.repositories``, never mapped onto domain objects directly.

The schema created here MUST match ``migrations/versions/`` exactly; each
Alembic migration is hand-written (not autogenerated) but mirrors the
corresponding table column-for-column. If the two ever drift, integration
tests comparing live database structure against this metadata will surface
it.
"""

from __future__ import annotations

import sqlalchemy as sa
from mrr.domain.delivery_retry import DELIVERY_RECORD_STATUSES
from mrr.domain.replay_retention import PROCESSED_ID_KINDS
from mrr.domain.repositories import EDGE_VOCABULARY
from mrr.provenance.log import OUTBOX_STATUSES
from sqlalchemy.dialects import postgresql

metadata = sa.MetaData()

#: The IN-list clause for the ``edges.edge_type`` CHECK constraint, built
#: from the single source of truth for the vocabulary
#: (``mrr.domain.repositories.EDGE_VOCABULARY``) so this table definition can
#: never silently drift from the domain-layer fail-closed check in
#: ``mrr.persistence.repositories.PostgresEdgeRepository.add_edge``. The
#: initial migration hard-codes the equivalent literal list (migrations must
#: be self-contained, reviewable snapshots that don't import application
#: code) — see the module docstring above for the drift-detection story.
_EDGE_TYPE_LIST = ", ".join(f"'{t}'" for t in sorted(EDGE_VOCABULARY))
_EDGE_TYPE_CHECK_CLAUSE = f"edge_type IN ({_EDGE_TYPE_LIST})"

#: One generic, revisioned object-store table. Every first-class MRR object
#: (docs/spec/02_DOMAIN_MODEL.md section 1) is a row here; ``(id, revision)``
#: is the primary key, so a revision is always a new row — there is no
#: UPDATE or DELETE path anywhere in ``mrr.persistence.repositories``.
objects_table = sa.Table(
    "objects",
    metadata,
    sa.Column("id", sa.Text(), nullable=False),
    sa.Column("revision", sa.Integer(), nullable=False),
    sa.Column("api_version", sa.Text(), nullable=False),
    sa.Column("kind", sa.Text(), nullable=False),
    sa.Column("practice_id", sa.Text(), nullable=False),
    sa.Column("created_at", sa.TIMESTAMP(timezone=True), nullable=False),
    sa.Column("created_by", sa.Text(), nullable=False),
    sa.Column("content_hash", sa.Text(), nullable=False),
    sa.Column("supersedes", sa.Text(), nullable=True),
    sa.Column("labels", postgresql.JSONB(), nullable=True),
    sa.Column("body", postgresql.JSONB(), nullable=False),
    sa.PrimaryKeyConstraint("id", "revision", name="pk_objects"),
    sa.Index("ix_objects_kind", "kind"),
)

#: One generic typed-edge table for the claim/evidence graph
#: (docs/spec/02_DOMAIN_MODEL.md section 3). Edges are not revisioned — each
#: row is independent and append-only, identified by its own urn.
edges_table = sa.Table(
    "edges",
    metadata,
    sa.Column("id", sa.Text(), nullable=False),
    sa.Column("source_id", sa.Text(), nullable=False),
    sa.Column("target_id", sa.Text(), nullable=False),
    sa.Column("edge_type", sa.Text(), nullable=False),
    sa.Column("created_at", sa.TIMESTAMP(timezone=True), nullable=False),
    sa.Column("created_by", sa.Text(), nullable=False),
    sa.Column("practice_id", sa.Text(), nullable=True),
    sa.Column("scope", postgresql.JSONB(), nullable=True),
    sa.Column("status", sa.Text(), nullable=False),
    sa.PrimaryKeyConstraint("id", name="pk_edges"),
    sa.CheckConstraint(_EDGE_TYPE_CHECK_CLAUSE, name="ck_edges_edge_type_vocabulary"),
    sa.Index("ix_edges_source_id", "source_id"),
    sa.Index("ix_edges_target_id", "target_id"),
    sa.Index("ix_edges_edge_type", "edge_type"),
)

#: The IN-list clause for the ``outbox.status`` CHECK constraint, built from
#: the single source of truth for the vocabulary
#: (``mrr.provenance.log.OUTBOX_STATUSES``) — mirrors the
#: ``_EDGE_TYPE_CHECK_CLAUSE`` pattern above.
_OUTBOX_STATUS_LIST = ", ".join(f"'{s}'" for s in sorted(OUTBOX_STATUSES))
_OUTBOX_STATUS_CHECK_CLAUSE = f"status IN ({_OUTBOX_STATUS_LIST})"

#: The append-only domain event log (task-packets/E1-T06.yaml, MRR-NFR-002).
#: ``sequence`` is a database-generated identity so append order is decided
#: by the database itself, never by application code — there is no UPDATE or
#: DELETE path anywhere in ``mrr.persistence.repositories.PostgresEventLog``.
#: ``prev_hash`` is NULL only for the very first physical row ever inserted;
#: every later row's ``prev_hash`` is the previous row's ``content_hash``
#: (task-packets/E1-T06.yaml derived_decisions: "tamper evidence is a hash
#: chain").
domain_events_table = sa.Table(
    "domain_events",
    metadata,
    sa.Column("sequence", sa.BigInteger(), sa.Identity(always=True), nullable=False),
    sa.Column("id", sa.Text(), nullable=False),
    sa.Column("event_type", sa.Text(), nullable=False),
    sa.Column("occurred_at", sa.TIMESTAMP(timezone=True), nullable=False),
    sa.Column("actor", sa.Text(), nullable=False),
    sa.Column("policy_version", sa.Text(), nullable=False),
    sa.Column("causation_id", sa.Text(), nullable=True),
    sa.Column("correlation_id", sa.Text(), nullable=False),
    sa.Column("object_id", sa.Text(), nullable=False),
    sa.Column("object_revision", sa.Integer(), nullable=False),
    sa.Column("payload", postgresql.JSONB(), nullable=False),
    sa.Column("content_hash", sa.Text(), nullable=False),
    sa.Column("prev_hash", sa.Text(), nullable=True),
    sa.PrimaryKeyConstraint("sequence", name="pk_domain_events"),
    sa.UniqueConstraint("id", name="uq_domain_events_id"),
    sa.Index("ix_domain_events_object_id", "object_id"),
    sa.Index("ix_domain_events_correlation_id", "correlation_id"),
)

#: The transactional outbox (task-packets/E1-T06.yaml, docs/spec/03_API_AND_
#: EVENTS.md section 5.3: "State changes and event publication MUST use a
#: transactional outbox so that committed domain changes cannot silently
#: lose their corresponding event"). One row per appended event, inserted in
#: the SAME transaction as its ``domain_events`` row
#: (``mrr.persistence.unit_of_work.record_object_revision_with_event``).
#: There is no UPDATE path that changes ``event_id`` or re-creates a
#: dispatched row — ``mrr.persistence.repositories.InProcessOutboxDispatcher``
#: only ever transitions a row's ``status``/``dispatched_at``/``attempts``.
outbox_table = sa.Table(
    "outbox",
    metadata,
    sa.Column("event_id", sa.Text(), nullable=False),
    sa.Column("status", sa.Text(), nullable=False),
    sa.Column("created_at", sa.TIMESTAMP(timezone=True), nullable=False),
    sa.Column("dispatched_at", sa.TIMESTAMP(timezone=True), nullable=True),
    sa.Column("attempts", sa.Integer(), nullable=False, server_default=sa.text("0")),
    sa.PrimaryKeyConstraint("event_id", name="pk_outbox"),
    sa.ForeignKeyConstraint(["event_id"], ["domain_events.id"], name="fk_outbox_event_id"),
    sa.CheckConstraint(_OUTBOX_STATUS_CHECK_CLAUSE, name="ck_outbox_status_vocabulary"),
)

#: The IN-list clause for the ``processed_ids.id_kind`` CHECK constraint,
#: built from the single source of truth
#: (``mrr.domain.replay_retention.PROCESSED_ID_KINDS``) — mirrors
#: ``_EDGE_TYPE_CHECK_CLAUSE``/``_OUTBOX_STATUS_CHECK_CLAUSE`` above.
_PROCESSED_ID_KIND_LIST = ", ".join(f"'{k}'" for k in PROCESSED_ID_KINDS)
_PROCESSED_ID_KIND_CHECK_CLAUSE = f"id_kind IN ({_PROCESSED_ID_KIND_LIST})"

#: The durable processed-id store (task-packets/E5-T07.yaml) backing
#: ``mrr.domain.envelope_validation.AlreadyProcessed`` (over ``message_id``)
#: and ``mrr.domain.offline_bundle.BundleAlreadyProcessed`` (over
#: ``bundle_id``) — one table, discriminated by ``id_kind``, rather than two
#: near-identical tables, since the two id spaces are already distinct URN
#: entity segments and cannot collide.
#:
#: Keyed by ``(recipient_node_id, id)``, NOT ``id`` alone: replay detection
#: is per RECEIVING node — the same object id delivered to two different
#: nodes is not a replay at either. That pair is this table's primary key,
#: which is also its UNIQUE constraint and the single idempotency anchor
#: ``mrr.persistence.repositories.PostgresProcessedIdStore.record_processed``
#: relies on (``INSERT ... ON CONFLICT DO NOTHING`` targets exactly this
#: constraint, so a duplicate insert is a silent no-op at the database, never
#: an application-level check that could race).
#:
#: ``expires_at`` is the recorded object's own expiry (copied from the
#: envelope/bundle at record time), stored so
#: ``mrr.domain.replay_retention.processed_id_retention_horizon`` can be
#: evaluated per row without re-fetching the original object — retention is
#: therefore safe by construction and can never prune a row while an object
#: bearing its id could still pass its own validity-window check. There is
#: no UPDATE path anywhere in ``PostgresProcessedIdStore``: a row is
#: appended once by ``record_processed`` and later removed only by
#: ``prune_expired`` — append-then-prune only, never mutated in place.
processed_ids_table = sa.Table(
    "processed_ids",
    metadata,
    sa.Column("id", sa.Text(), nullable=False),
    sa.Column("id_kind", sa.Text(), nullable=False),
    sa.Column("recipient_node_id", sa.Text(), nullable=False),
    sa.Column("processed_at", sa.TIMESTAMP(timezone=True), nullable=False),
    sa.Column("expires_at", sa.TIMESTAMP(timezone=True), nullable=False),
    sa.PrimaryKeyConstraint("recipient_node_id", "id", name="pk_processed_ids"),
    sa.CheckConstraint(_PROCESSED_ID_KIND_CHECK_CLAUSE, name="ck_processed_ids_id_kind_vocabulary"),
    sa.Index("ix_processed_ids_expires_at", "expires_at"),
)

#: The durable, append-only revocation-fact store (task-packets/E5-T07b.yaml)
#: backing ``mrr.persistence.repositories.PostgresKeyRevocationStore`` and the
#: pure ``mrr.domain.trust_revocation.trust_revoked_after_creation`` predicate
#: — the first place in this codebase a revocation INSTANT is durably
#: captured at all (``mrr.domain.key_management.revoke`` only mutates an
#: in-memory ``KeyRing`` descriptor's ``state``, with no timestamp).
#:
#: Keyed by ``kid`` ALONE, not ``(practice_id, kid)`` — unlike
#: ``processed_ids_table`` (where the SAME id delivered to two different
#: RECEIVING nodes is legitimately not a replay at either, hence that
#: table's wider two-column key), a kid (``mrr.crypto.keys.derive_key_id``)
#: is already a content-derived, globally unique fingerprint of one specific
#: Ed25519 public key. The same key cannot legitimately belong to two
#: different practices, so "is this kid revoked" has exactly one true
#: answer, independent of who is asking. The primary key is also this
#: table's UNIQUE constraint and the sole idempotency anchor
#: ``PostgresKeyRevocationStore.record_revocation`` relies on
#: (``INSERT ... ON CONFLICT (kid) DO NOTHING`` targets exactly this
#: constraint, so a duplicate insert is a silent no-op at the database,
#: never an application-level check that could race).
#:
#: ``revoked_at`` is the instant the revocation takes effect —
#: caller-supplied, never generated internally, mirroring
#: ``processed_ids_table.processed_at``. ``reason`` is optional free text.
#: There is no UPDATE or DELETE path anywhere in
#: ``PostgresKeyRevocationStore`` — no such method exists on that class at
#: all — so a row, once inserted by ``record_revocation``, is permanent and
#: authoritative for the lifetime of the row: a second, differently-
#: parameterized call for the same ``kid`` is a silent no-op that leaves the
#: original row untouched.
key_revocations_table = sa.Table(
    "key_revocations",
    metadata,
    sa.Column("kid", sa.Text(), nullable=False),
    sa.Column("practice_id", sa.Text(), nullable=False),
    sa.Column("revoked_at", sa.TIMESTAMP(timezone=True), nullable=False),
    sa.Column("reason", sa.Text(), nullable=True),
    sa.PrimaryKeyConstraint("kid", name="pk_key_revocations"),
)

#: The IN-list clause for the ``pending_deliveries.status`` CHECK constraint,
#: built from the single source of truth
#: (``mrr.domain.delivery_retry.DELIVERY_RECORD_STATUSES``) — mirrors
#: ``_EDGE_TYPE_CHECK_CLAUSE``/``_OUTBOX_STATUS_CHECK_CLAUSE``/
#: ``_PROCESSED_ID_KIND_CHECK_CLAUSE`` above.
_DELIVERY_RECORD_STATUS_LIST = ", ".join(f"'{s}'" for s in DELIVERY_RECORD_STATUSES)
_DELIVERY_RECORD_STATUS_CHECK_CLAUSE = f"status IN ({_DELIVERY_RECORD_STATUS_LIST})"

#: The durable, per-recipient offline delivery-tracking store (task-packets/
#: E6-T06.yaml) backing ``mrr.persistence.repositories.
#: PostgresDeliveryPendingStore`` and the pure ``mrr.domain.delivery_retry``
#: narrow ``pending``/``delivered``/``exhausted`` machine — the "durable
#: pending-delivery record" half of MRR-FR-094. This is INTERNAL node state,
#: not a first-class, schema-validated cross-practice object (mirrors
#: ``processed_ids_table``'s own identical precedent, task-packets/
#: E5-T07.yaml: "a processed-id row is INTERNAL node state ... it gets NO
#: schema/contract/example").
#:
#: Keyed by ``(recipient_node_id, notification_id)``, NOT ``notification_id``
#: alone — mirrors ``processed_ids_table``'s own ``(recipient_node_id, id)``
#: shape exactly, substituting the correction notification's own stable
#: ``notification_id`` (independent of whichever envelope/bundle most
#: recently wrapped it) for the envelope/bundle id. That pair is this
#: table's primary key, which is also its UNIQUE constraint and the sole
#: idempotency anchor ``mrr.persistence.repositories.
#: PostgresDeliveryPendingStore.open_pending_delivery`` relies on
#: (``INSERT ... ON CONFLICT DO NOTHING`` targets exactly this constraint).
#:
#: Unlike ``processed_ids_table`` (append-then-prune-only), this table DOES
#: have an UPDATE path: ``record_retry_attempt``/``mark_exhausted`` mutate
#: ``status``/``attempt_count``/``last_attempted_at``/``next_retry_at``/
#: ``resolved_at``/``exhausted_reason`` in place on the SAME row — this
#: record genuinely needs controlled mutation, which is exactly why it is a
#: SEPARATE table from ``processed_ids_table`` rather than piggybacked onto
#: it (task-packets/E6-T06.yaml forbidden_changes). There is still no DELETE
#: path anywhere in ``PostgresDeliveryPendingStore`` — a resolved
#: (``delivered``/``exhausted``) record is never pruned, because the record
#: itself IS the durable audit fact MRR-FR-094 requires (task-packets/
#: E6-T06.yaml derived_decisions (c)).
#:
#: ``next_retry_at`` is indexed alongside ``status`` to support the
#: retry-due query's ``status = 'pending' AND next_retry_at <= now``
#: predicate. ``notification_expires_at`` is the wrapped notification's own
#: expiry, copied at ``open_pending_delivery`` time so
#: ``mrr.domain.delivery_retry.next_retry_at``/``is_retry_exhausted`` can be
#: evaluated per row without re-fetching the original notification — mirrors
#: ``processed_ids_table.expires_at``'s identical reasoning. The CHECK
#: constraint below additionally enforces, at the database level, that an
#: ``exhausted`` row always carries a non-null ``exhausted_reason`` — a
#: second, independent guard alongside ``PostgresDeliveryPendingStore.
#: mark_exhausted``'s own in-code "reason must be non-empty" check
#: (task-packets/E6-T06.yaml invariant: "delivery exhaustion is an explicit
#: recorded outcome, never a silent give-up").
pending_deliveries_table = sa.Table(
    "pending_deliveries",
    metadata,
    sa.Column("recipient_node_id", sa.Text(), nullable=False),
    sa.Column("notification_id", sa.Text(), nullable=False),
    sa.Column("correction_id", sa.Text(), nullable=False),
    sa.Column("status", sa.Text(), nullable=False),
    sa.Column("attempt_count", sa.Integer(), nullable=False),
    sa.Column("opened_at", sa.TIMESTAMP(timezone=True), nullable=False),
    sa.Column("last_attempted_at", sa.TIMESTAMP(timezone=True), nullable=False),
    sa.Column("next_retry_at", sa.TIMESTAMP(timezone=True), nullable=True),
    sa.Column("notification_expires_at", sa.TIMESTAMP(timezone=True), nullable=False),
    sa.Column("resolved_at", sa.TIMESTAMP(timezone=True), nullable=True),
    sa.Column("exhausted_reason", sa.Text(), nullable=True),
    sa.PrimaryKeyConstraint("recipient_node_id", "notification_id", name="pk_pending_deliveries"),
    sa.CheckConstraint(
        _DELIVERY_RECORD_STATUS_CHECK_CLAUSE, name="ck_pending_deliveries_status_vocabulary"
    ),
    sa.CheckConstraint(
        "status != 'exhausted' OR exhausted_reason IS NOT NULL",
        name="ck_pending_deliveries_exhausted_has_reason",
    ),
    sa.Index("ix_pending_deliveries_status_next_retry_at", "status", "next_retry_at"),
)
